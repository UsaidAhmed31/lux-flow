def lum(h):
    h = h.lstrip('#')
    if len(h) == 3: h = ''.join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def map_bg_hex(h):
    L = lum(h)
    if L < 0.06: return '#FFFFFF'      # near-black surfaces -> white
    if L < 0.12: return '#F1EEF8'      # raised dark surfaces -> soft lilac grey
    if L < 0.2: return '#E7E3F2'
    return None

def map_text_hex(h):
    L = lum(h)
    if L > 0.85: return 'var(--ink)'
    if L > 0.6: return 'var(--ink-2)'
    if L > 0.4: return 'var(--ink-3)'
    return None

KEEP_SEL = re.compile(r'\.btn|\.dock-create|\.seg button\.on|\.toggle|\.cal-day\.sel|\.pause-mark|\.gate-ic|\.send|\.msg\.me|\.chip\.on|\.side-badge|\.dock-dot|\.unread|\.admin-count|\.tag-rec|\.comm-hero|\.sys-preview|\.hero-strip \.chip\.on|\.pt\b|\.pt-|\.fig-stage|\.sc-|\.space|\.sun\b|\.sys-info|\.fig-veil|\.hero-focus|\.hf-|\.toast|\.overlay|\.sk\b|\.media|\.vbadge|\.radio|\.opt-row\.on \.radio|\.aud-opt\.on \.radio|\.ob-step\.done \.ob-check|\.av-\d|\.av-more|\.dot-|\.sys-(radiance|purpose|presence|wisdom|connection|unity|vitality|foundation|journey|remembrance)|\.empty-ic|\.beam|\.brand-ic|\.side-create|\.flow-entry-ic|\.type-ic|\.step-n|\.dock-item\.on|\.side-item\.on|\.cal-day\.sel \.cal-n')

def transform_decl(prop, val):
    p = prop.strip().lower(); v = val
    if p in ('background', 'background-color', 'background-image', 'fill'):
        nv = re.sub(r'#[0-9A-Fa-f]{6}\b|#[0-9A-Fa-f]{3}\b', lambda m: map_bg_hex(m.group(0)) or m.group(0), v)
        nv = re.sub(r'rgba\(\s*(10|14|4|20|15|12),\s*(9|12|3|8|17|18|10|11),\s*(18|23|10|24|30|46|22|19)\s*,\s*([.\d]+)\)', lambda m: 'rgba(255,255,255,%s)' % m.group(4), nv)
        nv = re.sub(r'rgba\(255,\s*255,\s*255,\s*(\.0\d+|\.1\d*)\)', lambda m: 'rgba(20,17,46,%s)' % m.group(1), nv)
        return nv if nv != v else None
    if p == 'color':
        nv = re.sub(r'#[0-9A-Fa-f]{6}\b', lambda m: map_text_hex(m.group(0)) or m.group(0), v)
        return nv if nv != v else None
    if p in ('border', 'border-color', 'border-top', 'border-bottom', 'border-left', 'border-right', 'outline'):
        nv = re.sub(r'#[0-9A-Fa-f]{6}\b', lambda m: 'var(--line-2)' if lum(m.group(0)) < 0.2 else m.group(0), v)
        return nv if nv != v else None
    if p == 'box-shadow':
        nv = re.sub(r'rgba\(0,\s*0,\s*0,\s*([.\d]+)\)', lambda m: 'rgba(40,30,90,%.2f)' % (float(m.group(1)) * 0.28), v)
        nv = re.sub(r'#(14121E|13111B|0F0D18|0A0912)', '#FFFFFF', nv)
        return nv if nv != v else None
    return None

out = []
def walk(block, media=None):
    i = 0
    while i < len(block):
        j = block.find('{', i)
        if j < 0: break
        sel = re.sub(r'/\*.*?\*/', '', block[i:j], flags=re.S).strip()
        if sel.startswith('@media') or sel.startswith('@supports'):
            depth = 1; k = j + 1
            while depth: depth += {'{': 1, '}': -1}.get(block[k], 0); k += 1
            walk(block[j + 1:k - 1], sel); i = k; continue
        if sel.startswith('@keyframes') or sel.startswith('@property') or sel.startswith('@font-face'):
            depth = 1; k = j + 1
            while depth: depth += {'{': 1, '}': -1}.get(block[k], 0); k += 1
            i = k; continue
        k = block.find('}', j); body = block[j + 1:k]; i = k + 1
        sel = re.sub(r'/\*.*?\*/', '', sel, flags=re.S).strip()
        if not sel or sel.startswith(':root'): continue
        decls = []
        for d in body.split(';'):
            if ':' not in d: continue
            prop, val = d.split(':', 1)
            nv = transform_decl(prop, val)
            if nv is not None: decls.append('%s:%s' % (prop.strip(), nv.strip()))
        if not decls: continue
        sels = [x.strip() for x in sel.split(',')]
        keep = [x for x in sels if not KEEP_SEL.search(x)]
        if not keep: continue
        scoped = ','.join('.app.theme-light ' + (x[5:] if x.startswith('.app ') else x) if not x.startswith('.app.') and x != '.app' else x.replace('.app', '.app.theme-light', 1) for x in keep)
        rule = scoped + '{' + ';'.join(decls) + '}'
        out.append('@media %s{ %s }' % (media[6:].strip(), rule) if media else rule)
walk(css)

